/**
 * Build the ASCII Themes plugin and its preview gallery.
 *
 * Inlines the scene library, renderer, whale density map, and the client wrapper
 * into one browser bundle, emits a complete plugin package to `dist/`, and writes
 * the static preview page.
 *
 *   node scripts/build.mjs
 */
import { readFile, writeFile, mkdir, rm, cp } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { execFileSync } from "node:child_process";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (path) => readFile(join(root, path), "utf8");

const packageName = "@local/dsh-ascii-themes";
const rowId = "ascii-themes";
const title = "ASCII Themes";
const description = "Choose a vibrant animated ASCII backdrop: whale, toxic skulls, azure peaks, Eden falls or orchard, golden valley, koi, jellyfish, or a neon sunset.";

const maskRows = (await read("src/whale-mask.txt"))
	.split("\n")
	.map((line) => line.trim())
	.filter(Boolean);
const maskWidth = maskRows[0].length;
for (const row of maskRows) {
	if (row.length !== maskWidth || /[^0-9]/.test(row)) throw new Error("malformed whale mask");
}

/** Inline a module body as script scope: drop only top-level `export` keywords. */
const inlineModule = (source) => source.replace(/^export\s+(?=function|class|const|let|var)/gm, "");

const scenes = inlineModule((await read("src/scenes.js")).replace("__WHALE_MASK__", JSON.stringify(maskRows)));
const renderer = inlineModule(await read("src/renderer.js"));
const clientTemplate = await read("src/client.template.js");
const previewTemplate = await read("src/preview.template.html");

for (const marker of ["__THEME_SCENES__", "__THEME_RENDERER__"]) {
	if (!clientTemplate.includes(marker)) throw new Error(`client template is missing ${marker}`);
}
const client = clientTemplate
	.replace("__THEME_SCENES__", scenes)
	.replace("__THEME_RENDERER__", renderer);
const preview = previewTemplate
	.replace("__THEME_SCENES__", scenes)
	.replace("__THEME_RENDERER__", renderer);

const dist = join(root, "dist");
await rm(dist, { recursive: true, force: true });
await mkdir(join(dist, "locale"), { recursive: true });

const manifest = {
	name: packageName,
	version: "1.0.0",
	private: true,
	type: "module",
	description,
	exports: {
		".": "./index.js",
		"./client": "./client.js",
		"./locale/*.json": "./locale/*.json",
		"./icon": "./icon.svg",
	},
	files: ["index.js", "client.js", "cordis.patch.yml", "locale/*.json", "icon.svg", "README.md"],
	dsh: {
		bundle: { patch: "./cordis.patch.yml" },
		client: { platform: "web", immediately: true, inject: ["@deepseek-ai/dsh-client-ui-layout"] },
	},
};
const patch = [
	"# Generated bundle patch: inserts the ASCII themes plugin row.",
	"- insert:",
	`    - id: ${rowId}`,
	`      name: '${packageName}'`,
	"      config: {}",
	"",
].join("\n");
const hostHalf = "/** Host half of the ASCII themes bundle; the Client module owns the rendering. */\nexport function apply() {}\n";
const localeEn = `${JSON.stringify({ meta: { title, description } }, null, 2)}\n`;
const localeZh = `${JSON.stringify({
	meta: {
		title: "ASCII 主题",
		description: "选择动态 ASCII 背景：鲸鱼、毒骷髅、云层、锦鲤、水母或霓虹日落。",
	},
}, null, 2)}\n`;
const readme = [
	`# ${title}`,
	"",
	description,
	"",
	"Generated by `scripts/build.mjs` from the sources in this directory. The floating",
	"palette at the bottom-right of the Web UI switches scenes; the choice is saved in",
	"browser storage.",
	"",
].join("\n");

await Promise.all([
	writeFile(join(dist, "client.js"), client, "utf8"),
	writeFile(join(dist, "package.json"), `${JSON.stringify(manifest, null, 2)}\n`, "utf8"),
	writeFile(join(dist, "cordis.patch.yml"), patch, "utf8"),
	writeFile(join(dist, "index.js"), hostHalf, "utf8"),
	writeFile(join(dist, "locale", "en.json"), localeEn, "utf8"),
	writeFile(join(dist, "locale", "zh.json"), localeZh, "utf8"),
	writeFile(join(dist, "README.md"), readme, "utf8"),
	cp(join(root, "assets", "icon.svg"), join(dist, "icon.svg")),
	writeFile(join(root, "preview.html"), preview, "utf8"),
]);
execFileSync(process.execPath, ["--check", join(dist, "client.js")], { stdio: "inherit" });

console.log(`built ${packageName} -> dist/ (${maskWidth}x${maskRows.length} whale mask)`);
console.log("built preview.html");
